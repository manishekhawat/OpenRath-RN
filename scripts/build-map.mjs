// Builds src/map/mapHtml.ts from assets/map: the Android version's own map page (Leaflet,
// leaflet-rotate and the QR code library), inlined into one HTML string so the WebView needs no
// file access. Run `npm run map` after changing anything in assets/map.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'assets', 'map');
const read = (f) => readFileSync(join(dir, f), 'utf8');

let html = read('map.html');
// a closing script tag inside the inlined code would end the script early
const safe = (js) => js.replace(/<\/script/gi, '<\\/script');
html = html.replace('<link rel="stylesheet" href="leaflet.css">', () => `<style>\n${read('leaflet.css')}\n</style>`);
for (const f of ['leaflet.js', 'qrcode.js', 'leaflet-rotate.js']) {
  html = html.replace(`<script src="${f}"></script>`, () => `<script>\n${safe(read(f))}\n</script>`);
}
if (/<(script|link)[^>]+(src|href)="(?!https?:)/.test(html)) throw new Error('map.html still links a local file');

const out =
  '// Generated by scripts/build-map.mjs from assets/map. Do not edit by hand.\n' +
  '/* eslint-disable */\n' +
  `export const MAP_HTML: string = ${JSON.stringify(html)};\n`;
writeFileSync(join(root, 'src', 'map', 'mapHtml.ts'), out);
console.log(`src/map/mapHtml.ts: ${(out.length / 1024).toFixed(0)} KB`);
